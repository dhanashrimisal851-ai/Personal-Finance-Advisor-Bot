from datetime import date
from flask import Blueprint, render_template, request, jsonify, session
from models import db, Budget, Expense
from routes.auth import login_required
from utils.validators import validate_positive_number
from utils.calculations import get_budget_performance

budget_bp = Blueprint("budget", __name__)

@budget_bp.route("/budget")
@login_required
def budget_view():
    return render_template("budget.html")

@budget_bp.route("/api/budget", methods=["GET"])
@login_required
def get_budgets():
    user_id = session["user_id"]
    today = date.today()
    try:
        month = int(request.args.get("month", today.month))
        year = int(request.args.get("year", today.year))
    except ValueError:
        month, year = today.month, today.year

    perf = get_budget_performance(user_id, month, year)
    return jsonify({
        "success": True,
        "month": month,
        "year": year,
        "performance": perf,
        "valid_categories": Budget.VALID_CATEGORIES
    })

@budget_bp.route("/api/budget", methods=["POST"])
@login_required
def set_budget():
    user_id = session["user_id"]
    data = request.get_json() or {}

    valid_amt, amount = validate_positive_number(data.get("amount"))
    if not valid_amt:
        return jsonify({"error": "Please enter a valid positive budget limit."}), 400

    category = (data.get("category") or "").strip()
    if category not in Budget.VALID_CATEGORIES:
        return jsonify({"error": f"Invalid category. Choose from: {', '.join(Budget.VALID_CATEGORIES)}"}), 400

    today = date.today()
    try:
        month = int(data.get("month", today.month))
        year = int(data.get("year", today.year))
    except ValueError:
        month, year = today.month, today.year

    # Check if budget already exists for this category/month/year
    existing = Budget.query.filter_by(
        user_id=user_id,
        category=category,
        month=month,
        year=year
    ).first()

    try:
        if existing:
            existing.amount = amount
            db.session.commit()
            return jsonify({"success": True, "message": f"Updated budget for {category} to ₹{amount:,.0f}!", "budget": existing.to_dict()})
        else:
            budget = Budget(
                user_id=user_id,
                category=category,
                amount=amount,
                month=month,
                year=year
            )
            db.session.add(budget)
            db.session.commit()
            return jsonify({"success": True, "message": f"Budget set for {category}: ₹{amount:,.0f}!", "budget": budget.to_dict()}), 201
    except Exception as e:
        db.session.rollback()
        return jsonify({"error": f"Failed to save budget: {str(e)}"}), 500

@budget_bp.route("/api/budget/<int:budget_id>", methods=["PUT"])
@login_required
def update_budget(budget_id):
    user_id = session["user_id"]
    budget = Budget.query.filter_by(id=budget_id, user_id=user_id).first()
    if not budget:
        return jsonify({"error": "Budget record not found."}), 404

    data = request.get_json() or {}
    if "amount" in data:
        valid_amt, amount = validate_positive_number(data["amount"])
        if not valid_amt:
            return jsonify({"error": "Budget amount must be positive."}), 400
        budget.amount = amount

    try:
        db.session.commit()
        return jsonify({"success": True, "message": "Budget updated successfully!", "budget": budget.to_dict()})
    except Exception as e:
        db.session.rollback()
        return jsonify({"error": f"Failed to update budget: {str(e)}"}), 500

@budget_bp.route("/api/budget/<int:budget_id>", methods=["DELETE"])
@login_required
def delete_budget(budget_id):
    user_id = session["user_id"]
    budget = Budget.query.filter_by(id=budget_id, user_id=user_id).first()
    if not budget:
        return jsonify({"error": "Budget record not found."}), 404

    try:
        db.session.delete(budget)
        db.session.commit()
        return jsonify({"success": True, "message": "Budget removed successfully."})
    except Exception as e:
        db.session.rollback()
        return jsonify({"error": f"Failed to remove budget: {str(e)}"}), 500

@budget_bp.route("/api/budget/apply-plan", methods=["POST"])
@login_required
def apply_ai_plan():
    """Applies a list of category allocations generated by AI directly to the user's budget."""
    user_id = session["user_id"]
    data = request.get_json() or {}
    allocations = data.get("allocations", [])
    today = date.today()
    month = int(data.get("month", today.month))
    year = int(data.get("year", today.year))

    if not allocations:
        return jsonify({"error": "No allocations provided to apply."}), 400

    applied_count = 0
    try:
        for item in allocations:
            cat = item.get("category")
            amt = float(item.get("amount", 0))
            if cat in Budget.VALID_CATEGORIES and amt > 0:
                existing = Budget.query.filter_by(user_id=user_id, category=cat, month=month, year=year).first()
                if existing:
                    existing.amount = amt
                else:
                    new_b = Budget(user_id=user_id, category=cat, amount=amt, month=month, year=year)
                    db.session.add(new_b)
                applied_count += 1
        db.session.commit()
        return jsonify({"success": True, "message": f"Successfully applied AI budget for {applied_count} categories!"})
    except Exception as e:
        db.session.rollback()
        return jsonify({"error": f"Failed to apply budget: {str(e)}"}), 500
